function buildGraphReadme(g: GraphSpec): string {
  return `# ${g.name}

> **Framework**: \`${g.framework}\`  
> **Type**: \`${g.graphType}\`  
> **Category**: ${g.category}  
> **Difficulty**: ${g.difficulty}  
> **Nodes**: ${g.nodeCount} | **Edges**: ${g.edgeCount}  
> **Streaming**: ${g.supportsStreaming ? "✅" : "❌"} | **Human-in-Loop**: ${g.supportsHumanInLoop ? "✅" : "❌"}  
${g.sourceRepo ? `> **Source**: [${g.sourceRepo}](https://github.com/${g.sourceRepo})` : ""}

## Description

${g.description}

## Graph Topology

### Nodes

| ID | Label | Type |
|----|-------|------|
${g.nodes.map((n) => `| \`${n.id}\` | ${n.label} | \`${n.type}\` |`).join("\n")}

### Edges

| From | To | Condition |
|------|----|-----------|
${g.edges.map((e) => `| \`${e.from}\` | \`${e.to}\` | ${e.label ?? (e.conditional ? "conditional" : "always")} |`).join("\n")}

## Use Cases

${g.useCases.map((u) => `- ${u}`).join("\n")}

## Tags

${g.tags.join(", ")}

## License

${g.license}
`;
}

async function main() {
  console.log("================================================================");
  console.log("⚡ CORALNEST — AI AGENT GRAPH HARVESTER");
  console.log(`   Target: ${GRAPHS.length} graphs from LangGraph, AutoGen, CrewAI, Custom`);
  console.log("   Storage: B2 + CockroachDB graphs table");
  console.log("================================================================\n");

  let processed = 0;
  let errors = 0;

  for (const g of GRAPHS) {
    try {
      const graphSlug = g.slug;
      const b2Prefix = `graphs/${g.framework}/${graphSlug}`;

      let readme: string | null = null;
      if (g.sourceRepo) {
        const [owner, repo] = g.sourceRepo.split("/");
        readme = await fetchGitHubReadme(owner, repo);
      }
      if (!readme) {
        readme = buildGraphReadme(g);
      }

      const graphJson = JSON.stringify(g, null, 2);

      const {
        bytes,
        hash,
        url: storageUrl,
      } = await b2Upload(`${b2Prefix}/graph.json`, graphJson, "application/json");
      await b2Upload(`${b2Prefix}/README.md`, readme, "text/markdown; charset=utf-8");

      const tags = extractTags(g.description, g.tags);
      const qualityScore = computeQuality({
        hasDescription: !!g.description,
        descriptionLength: g.description.length,
        hasTags: tags.length >= 3,
        tagCount: tags.length,
        hasLicense: !!g.license,
        hasIcon: false,
        hasSourceRepo: !!g.sourceRepo,
        hasReadme: true,
        trust: g.framework !== "custom" ? "verified" : "community",
      });

      await sql`
        INSERT INTO graphs (
          id, slug, name,
          source, source_id, external_url, source_repo,
          graph_type, entry_node, node_count, edge_count,
          framework, supports_streaming, supports_human_in_loop,
          category, subcategory, tags, compatibility, use_cases, difficulty,
          summary, author, license,
          quality_score, security_score, is_verified, is_featured, is_deprecated,
          downloads, stars,
          storage_path, storage_url, content_hash, file_size_bytes,
          last_synced_at
        ) VALUES (
          ${g.id}, ${graphSlug}, ${g.name},
          ${g.framework}, ${g.id}, ${g.externalUrl ?? null}, ${g.sourceRepo ?? null},
          ${g.graphType}, ${g.entryNode}, ${g.nodeCount}, ${g.edgeCount},
          ${g.framework}, ${g.supportsStreaming}, ${g.supportsHumanInLoop},
          ${g.category}, ${g.subcategory}, ${tags},
          ${["langchain", "langgraph", "autogen", "crewai", "custom", "any"]},
          ${g.useCases}, ${g.difficulty},
          ${g.description.slice(0, 500)}, ${g.author}, ${g.license},
          ${qualityScore}, ${85}, ${g.framework !== "custom"}, ${qualityScore >= 80}, ${false},
          ${0}, ${0},
          ${b2Prefix + "/graph.json"}, ${storageUrl}, ${hash}, ${bytes},
          ${new Date().toISOString()}
        )
        ON CONFLICT (slug) DO UPDATE SET
          quality_score = EXCLUDED.quality_score,
          storage_url = EXCLUDED.storage_url,
          content_hash = EXCLUDED.content_hash,
          last_synced_at = EXCLUDED.last_synced_at
      `;

      processed++;
      process.stdout.write(
        `   [${String(processed).padStart(2)}/${GRAPHS.length}] ✅ ${g.name.slice(0, 55).padEnd(55)}\r`,
      );
    } catch (e: any) {
      errors++;
      console.error(`\n   ❌ Error on ${g.slug}: ${e.message}`);
    }
    await sleep(40);
  }

  const dbCount = await sql`SELECT count(*) AS c FROM graphs`;

  console.log("\n\n================================================================");
  console.log("🎉 AI AGENT GRAPH HARVEST COMPLETE");
  console.log(`   Graphs Processed:  ${processed}/${GRAPHS.length}`);
  console.log(`   Errors:            ${errors}`);
  console.log(`   Total DB Graphs:   ${dbCount[0].c} rows in CockroachDB`);
  console.log(`   Frameworks:        LangGraph, AutoGen, CrewAI, Custom`);
  console.log("================================================================");
  await sql.end();
}

void main().catch((e) => {
  console.error("❌ Fatal:", e);
  process.exit(1);
});
